const mongoose = require('mongoose');

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: [true, 'Name is required'],
      trim: true,
      maxlength: [100, 'Name cannot exceed 100 characters'],
    },
    email: {
      type: String,
      required: [true, 'Email is required'],
      unique: true,
      lowercase: true,
      trim: true,
      match: [/^\S+@\S+\.\S+$/, 'Please enter a valid email'],
    },
    mobile: {
      type: String,
      required: [true, 'Mobile number is required'],
      trim: true,
      match: [/^[6-9]\d{9}$/, 'Please enter a valid 10-digit Indian mobile number'],
    },
    password: {
      type: String,
      default: null, // null until user completes SetPassword step
      select: false,  // never returned in queries by default
    },
    role: {
      type: String,
      enum: ['farmer', 'buyer', 'expert', 'admin'],
      required: [true, 'Role is required'],
    },
    emailVerified: {
      type: Boolean,
      default: false,
    },
    // "active" = normal user, "pending" = expert awaiting admin approval,
    // "rejected" = expert rejected, "suspended" = admin suspended
    status: {
      type: String,
      enum: ['active', 'pending', 'rejected', 'suspended'],
      default: function () {
        return this.role === 'expert' ? 'pending' : 'active';
      },
    },
    // Login ID generated by the system (e.g. AV-F-00001)
    loginId: {
      type: String,
      unique: true,
      sparse: true, // allows null during registration before ID is generated
    },
    // Expert-specific fields
    expertInfo: {
      specialization: { type: String, default: null },
      qualifications: { type: String, default: null },
      experience: { type: String, default: null },
      organization: { type: String, default: null },
      documentUrls: [{ type: String }], // uploaded qualification docs
    },

        // Home location shown/used as the default for weather advice (farmers)
    location: {
      state:    { type: String, trim: true, maxlength: [60, 'State is too long'], default: null },
      district: { type: String, trim: true, maxlength: [100, 'District is too long'], default: null },
    },
    
    // Admin rejection reason for experts
    rejectionReason: {
      type: String,
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

// Indexes
userSchema.index({ email: 1 });
userSchema.index({ loginId: 1 });
userSchema.index({ role: 1, status: 1 });

module.exports = mongoose.model('User', userSchema);
